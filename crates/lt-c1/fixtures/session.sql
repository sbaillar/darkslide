-- A tiny synthetic Capture One 23 session database (no personal data).
-- Tables and columns are a subset of C1 16.1's schema (same names and types);
-- see docs/C1_FORMAT.md. Folder layout it describes:
--   a.ARW            two variants: VAR-A1 (rated 4, red, edited), VAR-A2 (green)
--   b.ARW            one variant, no .cos file (read from here)
--   Selects/c.ARW    rated 2
--   Trash/d.ARW      rated 5 (C1's trash)
--   /Volumes/Elsewhere/e.ARW  outside the session folder
CREATE TABLE ZDOCUMENTCONTENT ( Z_ENT INTEGER, Z_PK INTEGER PRIMARY KEY, ZDOCUMENTTYPE INTEGER NOT NULL, ZDOCUMENTUUID VARCHAR, ZROOTCOLLECTION INTEGER );
CREATE TABLE ZVERSIONINFO ( Z_ENT INTEGER, Z_PK INTEGER PRIMARY KEY, ZAUTHOR VARCHAR, ZVERSION INTEGER );
CREATE TABLE ZENTITIES ( Z_ENT INTEGER PRIMARY KEY, ZNAME VARCHAR );
CREATE TABLE ZCOLLECTION ( Z_ENT INTEGER, Z_PK INTEGER PRIMARY KEY, ZNAME VARCHAR, ZPARENT INTEGER, ZFOLDERLOCATION INTEGER, ZSMARTCRITERIA VARCHAR );
CREATE TABLE ZKEYWORD ( Z_ENT INTEGER, Z_PK INTEGER PRIMARY KEY, ZNAME VARCHAR, ZPARENT INTEGER, ZLEFT INTEGER UNIQUE, ZRIGHT INTEGER UNIQUE );
CREATE TABLE ZIMAGE ( Z_ENT INTEGER, Z_PK INTEGER PRIMARY KEY, ZIMAGEUUID VARCHAR, ZDISPLAYNAME VARCHAR, ZIMAGELOCATION INTEGER, ZIMAGEFILENAME VARCHAR, ZISTRASHED BOOLEAN, ZWIDTH INTEGER, ZHEIGHT INTEGER );
CREATE TABLE ZIMAGEINCOLLECTION ( Z_ENT INTEGER NOT NULL, Z_PK INTEGER PRIMARY KEY NOT NULL, ZCOLLECTION INTEGER NOT NULL, ZIMAGE INTEGER NOT NULL );
CREATE TABLE ZVARIANTINCOLLECTION ( Z_ENT INTEGER NOT NULL, Z_PK INTEGER PRIMARY KEY NOT NULL, ZCOLLECTION INTEGER NOT NULL, ZVARIANT INTEGER NOT NULL );
CREATE TABLE ZPATHLOCATION ( Z_ENT INTEGER, Z_PK INTEGER PRIMARY KEY, ZWINROOT VARCHAR, ZMACROOT VARCHAR, ZRELATIVEPATH VARCHAR, ZISRELATIVE BOOLEAN, ZVOLUME VARCHAR );
CREATE TABLE ZVARIANT ( Z_ENT INTEGER, Z_PK INTEGER PRIMARY KEY, ZINDEX INTEGER, ZVARIANTUUID VARCHAR, ZADJUSTMENTLAYER INTEGER, ZCOMBINEDSETTINGS INTEGER, ZDEFAULTLAYER INTEGER, ZIMAGE INTEGER, ZISMODIFIED BOOLEAN, ZCANVASSIZE VARCHAR );
CREATE TABLE ZVARIANTLAYER ( Z_ENT INTEGER, Z_PK INTEGER PRIMARY KEY, ZINDEX INTEGER, ZMETADATA INTEGER, ZVARIANT INTEGER, ZBRIGHTNESS FLOAT, ZCONTRAST FLOAT, ZCROP VARCHAR, ZEXPOSURE FLOAT, ZHIGHLIGHTRECOVERY FLOAT, ZROTATION FLOAT, ZSATURATION FLOAT, ZSHADOWRECOVERY FLOAT, ZWHITEBALANCE VARCHAR, ZFLIP INTEGER, ZLENSVIGNETTING VARCHAR, ZCROPASPECTRATIONAME VARCHAR, ZWHITERECOVERY FLOAT, ZBLACKRECOVERY FLOAT );
CREATE TABLE ZVARIANTMETADATA ( Z_ENT INTEGER, Z_PK INTEGER PRIMARY KEY, ZLAYER INTEGER, ZBASIC_RATING INTEGER, ZBASIC_LABEL VARCHAR, ZCONTENT_KEYWORDS VARCHAR, ZCOLOR_TAG_INDEX INTEGER );

